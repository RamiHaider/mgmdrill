"""Import 26-27_DrillTracking_<date>.xlsx into SQL for the mgmdrill Supabase project.

Usage:  python -I tools/import_tracker.py <tracker.xlsx> [out.sql]
Writes supabase/seed/tracker_seed.sql (gitignored: collars and results are confidential).
Run the SQL in the Supabase SQL editor after schema.sql.
"""
import sys, re, datetime as dt
from pathlib import Path
import openpyxl

SRC = Path(sys.argv[1])
OUT = Path(sys.argv[2]) if len(sys.argv) > 2 else Path(__file__).resolve().parents[1] / "supabase/seed/tracker_seed.sql"
wb = openpyxl.load_workbook(SRC, data_only=True)

RIG_ALIASES = {
    "RJLL - FSD15": "FSD15", "RJLL - FSD23": "FSD23", "RJLL - FSD27": "FSD27", "RJLL - FSD39": "FSD39",
    "Spektra - Foreuse No11": "No11",
    "FSD-15": "FSD15", "FSD-23": "FSD23", "FSD-27": "FSD27", "FSD-39": "FSD39",
    "RJLL FSD15": "FSD15", "RJLL FSD23": "FSD23", "RJLL FSD27": "FSD27", "RJLL FSD39": "FSD39", "SPEKTRA 11": "No11",
}
VIBES = {"bad": "Bad", "neutral": "Neutral", "ok": "Ok", "good": "Good", "excellent": "Excellent", "mortgage your house": "Mortgage your house"}
STATUSES = ["Permit Pending", "Planned", "Flagged", "Cut", "Spotted", "In Progress", "Complete", "Cancelled"]

def q(v):
    if v is None: return "null"
    if isinstance(v, bool): return "true" if v else "false"
    if isinstance(v, (int, float)): return repr(float(v)) if isinstance(v, float) else str(v)
    if isinstance(v, dt.datetime): return f"'{v.date().isoformat()}'"
    if isinstance(v, dt.date): return f"'{v.isoformat()}'"
    return "'" + str(v).replace("'", "''") + "'"

def num(v):
    if v is None or v == "": return None
    try: return float(v)
    except (TypeError, ValueError): return None

def s(v): return "" if v is None else str(v).strip()

def date(v):
    if isinstance(v, dt.datetime): return v.date()
    if isinstance(v, dt.date): return v
    return None

out = ["-- generated by tools/import_tracker.py from " + SRC.name + " on " + dt.date.today().isoformat(), "begin;"]

# ---------- holes: Joutel + Douay registers ----------
def parse_order(code):
    code = s(code)
    m = re.match(r"^([A-Za-z]+\d*)-(\d+)$", code)
    if not m: return None, None
    rig = m.group(1).upper()
    rig = {"R4": "FSD27", "R5": "FSD23", "NO11": "No11"}.get(rig, rig)   # R4/R5 are the sheet's shorthand for FSD27/FSD23
    return rig, int(m.group(2))

hole_rows = []
for sheet, project in (("Joutel", "joutel"), ("Douay", "douay")):
    ws = wb[sheet]
    hdr = [s(c).lower() for c in next(ws.iter_rows(min_row=1, max_row=1, values_only=True))]
    col = {h: i for i, h in enumerate(hdr) if h}
    def g(r, *names):
        for n in names:
            if n in col and col[n] < len(r): return r[col[n]]
        return None
    for r in ws.iter_rows(min_row=2, values_only=True):
        if not any(v not in (None, "") for v in r): continue
        pn, ddh = s(g(r, "planned name")), s(g(r, "ddh name"))
        if not pn and not ddh: continue
        status = s(g(r, "status")) or "Planned"
        if status not in STATUSES: status = "Planned"
        vibe = VIBES.get(s(g(r, "sentiment")).lower())
        rig, seq = parse_order(g(r, "order"))
        hole_rows.append(dict(
            project_id=project, planned_name=pn or None, zone=s(g(r, "zone")) or None, ddh_name=ddh or None,
            easting=num(g(r, "easting")), northing=num(g(r, "northing")), elevation=num(g(r, "elevation")),
            azimuth=num(g(r, "azimuth")), dip=num(g(r, "dip")), planned_depth=num(g(r, "planned depth")),
            start_length=num(g(r, "start length")) or 0, current_depth_manual=num(g(r, "current depth")),
            final_depth=num(g(r, "final depth")), n_samples=num(g(r, "no of  samples", "no of samples")),
            vibe=vibe, status=status, objective=s(g(r, "comment")), result=s(g(r, "result")),
            rig_id=rig, seq=seq, start_date=date(g(r, "start date")), end_date=date(g(r, "end date")), archived=False))

# Summary_Product carries start/end dates for the Joutel holes
ws = wb["Summary_Product"]
dates = {}
for r in ws.iter_rows(min_row=4, values_only=True):
    if len(r) > 12 and s(r[5]):
        dates[s(r[5]).lower()] = (date(r[11]), date(r[12]))
for h in hole_rows:
    if h["ddh_name"] and h["ddh_name"].lower() in dates:
        sd, ed = dates[h["ddh_name"].lower()]
        h["start_date"] = h["start_date"] or sd
        h["end_date"] = h["end_date"] or ed

# Archive = previous seasons
ws = wb["Archive"]
for r in ws.iter_rows(min_row=2, values_only=True):
    if not s(r[2]): continue
    hole_rows.append(dict(
        project_id=s(r[0]).lower(), planned_name=s(r[4]) or None, zone=s(r[1]) or None, ddh_name=s(r[2]),
        easting=num(r[5]), northing=num(r[6]), elevation=num(r[7]), azimuth=num(r[10]), dip=num(r[11]),
        planned_depth=None, start_length=num(r[13]) or 0, current_depth_manual=num(r[12]), final_depth=num(r[14]),
        n_samples=num(r[15]), vibe=None, status="Complete", objective="", result="", rig_id=None, seq=None,
        start_date=date(r[8]), end_date=date(r[9]), archived=True))

seen = set()
cols = ["project_id","planned_name","zone","ddh_name","easting","northing","elevation","azimuth","dip","planned_depth",
        "start_length","current_depth_manual","final_depth","n_samples","vibe","status","objective","result","rig_id","seq",
        "start_date","end_date","archived"]
out.append("-- holes")
for h in hole_rows:
    key = (h["project_id"], (h["ddh_name"] or "").lower())
    if h["ddh_name"]:
        if key in seen: continue
        seen.add(key)
    if h["n_samples"] is not None: h["n_samples"] = int(h["n_samples"])
    vals = ", ".join(q(h[c]) for c in cols)
    out.append(f"insert into holes ({', '.join(cols)}) values ({vals});")
print("holes:", len(hole_rows))

# ---------- timesheet ----------
ws = wb["Timesheet"]
row1 = [c for c in next(ws.iter_rows(min_row=1, max_row=1, values_only=True))]
blocks = []   # (rig_id, first_col_index)
for i, v in enumerate(row1):
    if isinstance(v, str) and v in RIG_ALIASES:
        blocks.append((RIG_ALIASES[v], i))
print("timesheet rigs:", blocks)
n_shift = 0
out.append("-- timesheet (source 'import': same rank as manual, contractor rows will overwrite)")
for r in ws.iter_rows(min_row=21, values_only=True):
    d = date(r[0]); shift = s(r[1]).lower()
    if not d or shift not in ("day", "night"): continue
    for rig, c in blocks:
        hole, st, en, tot, com = r[c], r[c+1], r[c+2], r[c+3], r[c+4]
        if not any(v not in (None, "", 0) for v in (hole, st, en, tot, com)): continue
        if not s(hole) and num(tot) in (None, 0) and num(en) is None: continue
        # pre-filled future rows (hole name carried forward, no end / total / comment) are not shifts yet
        if num(en) is None and num(tot) is None and not s(com): continue
        out.append("insert into shift_entries (rig_id, shift_date, shift, hole_name, start_m, end_m, total_m, comment, source) values "
                   f"({q(rig)}, {q(d)}, {q(shift)}, {q(s(hole) or None)}, {q(num(st))}, {q(num(en))}, {q(num(tot))}, {q(s(com))}, 'import');")
        n_shift += 1
print("shift rows:", n_shift)
# link hole_id by name
out.append("update shift_entries e set hole_id = h.id from holes h where e.hole_id is null and e.hole_name is not null and lower(h.ddh_name) = lower(e.hole_name) and not h.archived;")

# ---------- daily report (the one in the file) ----------
ws = wb["Daily Report"]
cells = {(c.row, c.column): c.value for row in ws.iter_rows() for c in row if c.value is not None}
def find(label):
    for (r, c), v in cells.items():
        if isinstance(v, str) and v.strip().upper() == label: return r, c
    return None
rd = find("REPORT DATE"); pt = find("PRODUCTION THROUGH")
report_date = date(cells.get((rd[0], rd[1] + 2))) if rd else None
through = date(cells.get((pt[0], pt[1] + 3))) if pt else None
if report_date:
    to_line = s(cells.get((find("TO")[0], find("TO")[1] + 2))) if find("TO") else ""
    weather = ""
    w = find("WEATHER")
    if w: weather = s(cells.get((w[0], w[1] + 2)))
    out.append(f"insert into daily_reports (report_date, production_through, to_line, weather) values ({q(report_date)}, {q(through)}, {q(to_line)}, {q(weather)}) on conflict (report_date) do nothing;")
    # per-rig geology + next target
    for (r, c), v in sorted(cells.items()):
        if isinstance(v, str) and "|" in v and c == 1 and v.split("|")[0].strip() in RIG_ALIASES:
            rig = RIG_ALIASES[v.split("|")[0].strip()]
            geo = nxt = ""
            for rr in range(r + 1, r + 8):
                lab = s(cells.get((rr, 1))).lower()
                if lab == "geology": geo = s(cells.get((rr, 3)))
                if lab == "next target": nxt = s(cells.get((rr, 3)))
            out.append(f"insert into rig_daily (report_date, rig_id, geology, next_target) values ({q(report_date)}, {q(rig)}, {q(geo)}, {q(nxt)}) on conflict do nothing;")
    rc = find("RC DRILLING")
    if rc:
        r = rc[0]
        vals = [cells.get((r + 2, c)) for c in (1, 4, 7, 10)]
        notes = [s(cells.get((rr, 1))) for rr in range(r + 3, r + 8) if s(cells.get((rr, 1))) and s(cells.get((rr, 1))).upper() != "OTHER"]
        data = {"holes_24h": num(vals[0]), "total_holes": num(vals[1]), "total_m": num(vals[2]), "samples": num(vals[3]), "notes": notes}
        import json
        out.append(f"insert into report_modules (report_date, kind, title, data, sort) values ({q(report_date)}, 'rc', 'RC drilling', {q(json.dumps(data))}::jsonb, 1);")
    ot = find("OTHER")
    if ot:
        r = ot[0]
        lines = [s(cells.get((rr, 1))) for rr in range(r + 1, r + 6) if s(cells.get((rr, 1))) and not s(cells.get((rr, 1))).upper().startswith("HSEC")]
        import json
        out.append(f"insert into report_modules (report_date, kind, title, data, sort) values ({q(report_date)}, 'other', 'Other', {q(json.dumps({'lines': lines}))}::jsonb, 2);")
print("daily report:", report_date, through)

# ---------- stats source ----------
ws = wb["STATS Source"]
n = 0
out.append("-- stats source")
for r in ws.iter_rows(min_row=2, values_only=True):
    if not s(r[1]) or not date(r[2]): continue
    out.append("insert into stats_source (project_id, drill_hole, reporting_date, meters, samples, source, include) values "
               f"({q(s(r[0]).lower())}, {q(s(r[1]))}, {q(date(r[2]))}, {q(num(r[3]) or 0)}, {int(num(r[4]) or 0)}, {q(s(r[5]) or 'Archive')}, {q(bool(num(r[6]) or 0))}) on conflict do nothing;")
    n += 1
print("stats rows:", n)

# ---------- consumables & standby ----------
ws = wb["Consumables & Standby"]
MONTHS = {m: i for i, m in enumerate(["jan","feb","mar","apr","may","jun","jul","aug","sep","oct","nov","dec"], 1)}
period = None; rig_cols = None; section = None; n = 0
out.append("-- consumables")
for r in ws.iter_rows(min_row=1, values_only=True):
    a = s(r[0]); b = s(r[1]) if len(r) > 1 else ""
    m = re.match(r"^([A-Za-z]{3})\w* (\d+) - ([A-Za-z]{3})\w* (\d+), (\d{4})", a)
    if m:
        y = int(m.group(5))
        period = (dt.date(y, MONTHS[m.group(1).lower()], int(m.group(2))), dt.date(y, MONTHS[m.group(3).lower()], int(m.group(4))))
        rig_cols = None; section = None; continue
    if b.lower() == "item":
        rig_cols = [(i, RIG_ALIASES.get(s(v), None)) for i, v in enumerate(r) if i >= 3 and s(v) and s(v).lower() != "total"]
        continue
    if a and not b and period:
        section = a.split("  -")[0].split(" -")[0].strip().title()
        continue
    if period and rig_cols and b:
        unit = s(r[2])
        for i, rig in rig_cols:
            if rig is None or i >= len(r): continue
            v = num(r[i])
            if v is None or v == 0: continue
            out.append("insert into consumables (period_start, period_end, rig_id, section, item, unit, qty, source) values "
                       f"({q(period[0])}, {q(period[1])}, {q(rig)}, {q(section or 'Other')}, {q(b)}, {q(unit)}, {v}, 'rjll_portal') on conflict do nothing;")
            n += 1
print("consumable rows:", n)

out.append("commit;")
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("\n".join(out), encoding="utf-8")
print("wrote", OUT, len(out), "statements")
